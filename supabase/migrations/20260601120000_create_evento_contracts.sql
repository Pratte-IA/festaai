returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.tenant_contract_templates (
    tenant_id, name, description, template_html, version, is_active, is_default
  )
  values (
    new.id,
    'Contrato padrão de festa infantil',
    'Modelo operacional base para contratação de festas.',
    $template$<article class="contract-document">
<h1>CONTRATO DE PRESTAÇÃO DE SERVIÇOS PARA FESTA INFANTIL</h1>
