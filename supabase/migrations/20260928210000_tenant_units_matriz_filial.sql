security definer
set search_path = public
as $$
  select id
  from public.tenant_units
  where tenant_id = p_tenant_id
    and kind = 'matriz'
  limit 1;
$$;

create or replace function public.enforce_tenant_unit_shape()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_parent public.tenant_units%rowtype;
begin
  if new.kind = 'matriz' then
    if new.parent_unit_id is not null then
      raise exception 'A matriz não referencia outra unidade.';
    end if;
    return new;
  end if;

  if new.parent_unit_id is null then
    raise exception 'A filial precisa apontar para a matriz do tenant.';
  end if;

  select * into v_parent
  from public.tenant_units
  where id = new.parent_unit_id;

  if v_parent.id is null or v_parent.tenant_id <> new.tenant_id or v_parent.kind <> 'matriz' then
    raise exception 'A filial só pode referenciar a matriz do mesmo tenant.';
  end if;

  return new;
end;
$$;

create trigger enforce_tenant_unit_shape
before insert or update on public.tenant_units
for each row execute function public.enforce_tenant_unit_shape();

