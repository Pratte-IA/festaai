create or replace function public.assign_tenant_unit_id()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_requested bigint;
  v_header text;
begin
  if new.tenant_id is null then
    if new.unit_id is not null then
      raise exception 'unit_id exige tenant_id';
    end if;
    return new;
  end if;

  if new.unit_id is not null then
    if not exists (
      select 1
      from public.tenant_units u
      where u.id = new.unit_id
        and u.tenant_id = new.tenant_id
    ) then
      raise exception 'A unidade % não pertence ao tenant %', new.unit_id, new.tenant_id;
    end if;
    return new;
  end if;

  v_header := public.request_header('x-festaai-unit-id');
  begin
    v_requested := v_header::bigint;
  exception
    when others then
      v_requested := null;
  end;

  if v_requested is not null and exists (
    select 1
    from public.tenant_units u
    where u.id = v_requested
      and u.tenant_id = new.tenant_id
  ) then
    new.unit_id := v_requested;
  else
    new.unit_id := public.tenant_matriz_unit_id(new.tenant_id);
  end if;

  if new.unit_id is null then
    raise exception 'O tenant % não tem matriz.', new.tenant_id;
  end if;

  return new;
end;
$$;

-- Tabelas com uma linha por casa: a chave passa a ser unit_id.
do $$
declare
  t text;
begin
  foreach t in array array[
    'tenant_company_profiles',
    'tenant_guided_setup_progress',
    'tenant_estrutura_settings',
    'tenant_financial_settings',
    'tenant_automation_settings',
    'tenant_contract_module_settings'
  ]
  loop
    execute format('alter table public.%I add column if not exists unit_id bigint', t);
    execute format(
      'update public.%I as row set unit_id = u.id from public.tenant_units u where row.tenant_id = u.tenant_id and u.kind = ''matriz'' and row.unit_id is null',
      t
    );
    execute format('alter table public.%I alter column unit_id set not null', t);
    execute format('alter table public.%I drop constraint if exists %I', t, t || '_pkey');
    execute format('alter table public.%I add primary key (unit_id)', t);
    execute format(
      'alter table public.%I drop constraint if exists %I',
      t,
      t || '_unit_id_fkey'
    );
    execute format(
      'alter table public.%I add constraint %I foreign key (unit_id) references public.tenant_units (id) on delete cascade',
      t,
      t || '_unit_id_fkey'
    );
    execute format('create index if not exists %I on public.%I (tenant_id)', t || '_tenant_idx', t);
  end loop;
end $$;

