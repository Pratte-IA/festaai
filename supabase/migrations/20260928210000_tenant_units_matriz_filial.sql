-- Matriz e filiais dentro do mesmo tenant.
-- O login, os membros e a assinatura continuam no tenant.
-- A casa (unidade) passa a ser o escopo de cadastro, operação, configuração e WhatsApp.

create table public.tenant_units (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants (id) on delete cascade,
  kind text not null,
  parent_unit_id bigint references public.tenant_units (id) on delete restrict,
  name text not null,
  slug text not null,
  document text,
  phone text,
  email text,
  status text not null default 'active',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_units_kind_check check (kind in ('matriz', 'filial')),
  constraint tenant_units_status_check check (status in ('active', 'inactive')),
  constraint tenant_units_slug_format_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint tenant_units_name_check check (char_length(btrim(name)) > 0),
  constraint tenant_units_tenant_slug_unique unique (tenant_id, slug)
);

create unique index tenant_units_one_matriz_idx
  on public.tenant_units (tenant_id)
  where kind = 'matriz';

create index tenant_units_tenant_id_idx on public.tenant_units (tenant_id);

create trigger set_tenant_units_updated_at
before update on public.tenant_units
for each row execute function public.set_updated_at();

comment on table public.tenant_units is
  'Casas do tenant. Uma matriz e zero ou mais filiais. O acesso continua sendo o do tenant.';

create or replace function public.tenant_matriz_unit_id(p_tenant_id bigint)
returns bigint
language sql
