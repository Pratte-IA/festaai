create or replace function public.create_tenant_filial(
  p_tenant_id bigint,
  p_name text,
  p_slug text
)
returns public.tenant_units
language plpgsql
security definer
set search_path = public
as $$
declare
  v_matriz_id bigint;
  v_unit public.tenant_units%rowtype;
begin
  if not (public.has_tenant_role(p_tenant_id, array['owner', 'admin']) or public.is_platform_admin()) then
    raise exception 'Sem permissão para criar filial.';
  end if;

  v_matriz_id := public.tenant_matriz_unit_id(p_tenant_id);
  if v_matriz_id is null then
    raise exception 'O tenant não tem matriz.';
  end if;

  insert into public.tenant_units (tenant_id, kind, parent_unit_id, name, slug, status)
  values (p_tenant_id, 'filial', v_matriz_id, btrim(p_name), p_slug, 'active')
  returning * into v_unit;

  insert into public.tenant_company_profiles (tenant_id, unit_id, company_name)
  values (p_tenant_id, v_unit.id, btrim(p_name))
  on conflict (unit_id) do nothing;

  insert into public.tenant_guided_setup_progress (tenant_id, unit_id, current_step, completed_steps)
  values (p_tenant_id, v_unit.id, 'company_profile', '{}')
  on conflict (unit_id) do nothing;

  insert into public.tenant_closing_form_fields (
    tenant_id, unit_id, section, label, field_key, field_type, required, active, sort_order, is_system,
    category, is_locked, usage_contract, usage_party_summary, usage_ai, usage_reports, usage_checklist,
    usage_internal_task, description, config, package_ids
  )
  select
    p_tenant_id, v_unit.id, section, label, field_key, field_type, required, active, sort_order, is_system,
    category, is_locked, usage_contract, usage_party_summary, usage_ai, usage_reports, usage_checklist,
    usage_internal_task, description, config, package_ids
  from public.tenant_closing_form_fields
  where unit_id = v_matriz_id
    and is_system = true
  on conflict (unit_id, field_key) do nothing;

  insert into public.tenant_payment_methods (
    tenant_id, unit_id, name, payment_type, allows_installments, max_installments,
    allowed_for_deposit, allowed_for_remaining_balance, active, sort_order
  )
  select
    p_tenant_id, v_unit.id, name, payment_type, allows_installments, max_installments,
    allowed_for_deposit, allowed_for_remaining_balance, active, sort_order
  from public.tenant_payment_methods
  where unit_id = v_matriz_id
  on conflict (unit_id, name) do nothing;

  insert into public.tenant_acceptance_terms (
    tenant_id, unit_id, term_key, title, content, is_required, appears_in_contract,
    is_system, active, sort_order, show_in_form, show_at_signing
  )
  select
    p_tenant_id, v_unit.id, term_key, title, content, is_required, appears_in_contract,
    is_system, active, sort_order, show_in_form, show_at_signing
  from public.tenant_acceptance_terms
  where unit_id = v_matriz_id
    and is_system = true
  on conflict (unit_id, term_key) do nothing;

  insert into public.tenant_satisfaction_survey_questions (
    tenant_id, unit_id, label, question_key, question_type, required, active, sort_order, config, is_system
  )
  select
    p_tenant_id, v_unit.id, label, question_key, question_type, required, active, sort_order, config, is_system
  from public.tenant_satisfaction_survey_questions
  where unit_id = v_matriz_id
    and is_system = true
  on conflict (unit_id, question_key) do nothing;

  return v_unit;
end;
$$;

