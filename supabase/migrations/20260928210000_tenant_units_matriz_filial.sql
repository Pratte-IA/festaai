create or replace function public.can_read_tenant_unit(
  p_tenant_id bigint,
  p_unit_id bigint,
  p_mode text
)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_requested bigint;
  v_scope text;
  v_header text;
begin
  if p_unit_id is null then
    return public.is_platform_admin();
  end if;

  if not (public.is_tenant_member(p_tenant_id) or public.is_platform_admin()) then
    return false;
  end if;

  if not exists (
    select 1
    from public.tenant_units u
    where u.id = p_unit_id
      and u.tenant_id = p_tenant_id
  ) then
    return false;
  end if;

  v_scope := coalesce(public.request_header('x-festaai-unit-scope'), 'one');
  v_header := public.request_header('x-festaai-unit-id');

  begin
    v_requested := v_header::bigint;
  exception
    when others then
      v_requested := null;
  end;

  if p_mode = 'operational' and v_scope = 'all' then
    return true;
  end if;

  if v_requested is not null and exists (
    select 1
    from public.tenant_units u
    where u.id = v_requested
      and u.tenant_id = p_tenant_id
  ) then
    return p_unit_id = v_requested;
  end if;

  return p_unit_id = public.tenant_matriz_unit_id(p_tenant_id);
end;
$$;

