-- Leitura pública de oferta ativa por token (via RPC security definer abaixo).

create or replace function public.get_public_commercial_offer(p_token text)
returns table (
  id bigint,
  token text,
  name text,
  base_plan_slug text,
  monthly_price numeric,
  setup_price numeric,
  setup_installments integer,
  loyalty_months integer,
  recipient_company text,
  recipient_email text,
  expires_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    o.id,
    o.token,
    o.name,
    o.base_plan_slug,
    o.monthly_price,
    o.setup_price,
    o.setup_installments,
    o.loyalty_months,
    o.recipient_company,
    o.recipient_email,
    o.expires_at
  from public.commercial_offers o
  where o.token = p_token
    and o.status = 'active'
    and o.expires_at > now()
  limit 1;
$$;

revoke all on function public.get_public_commercial_offer(text) from public;
grant execute on function public.get_public_commercial_offer(text) to anon, authenticated;

comment on table public.commercial_leads is 'Leads capturados pelo card Plano sob medida na página /contratar.';
comment on table public.commercial_offers is 'Propostas comerciais privadas com link exclusivo para formalização.';
