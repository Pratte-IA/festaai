create table public.tenant_satisfaction_survey_questions (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  label text not null,
  question_key text,
  question_type text not null default 'textarea',
  required boolean not null default false,
  active boolean not null default true,
  sort_order integer not null default 0,
  config jsonb not null default '{}'::jsonb,
  is_system boolean not null default false,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tenant_satisfaction_survey_questions_label_check check (char_length(trim(label)) > 0),
  constraint tenant_satisfaction_survey_questions_type_check check (
    question_type in ('scale', 'single_choice', 'textarea')
  ),
  constraint tenant_satisfaction_survey_questions_key_unique unique (tenant_id, question_key),
  constraint tenant_satisfaction_survey_questions_id_tenant_id_key unique (id, tenant_id)
);

create table public.evento_satisfaction_responses (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null references public.tenants(id) on delete cascade,
  evento_id bigint not null,
  question_id bigint not null,
  value text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint evento_satisfaction_responses_evento_tenant_fkey
    foreign key (evento_id, tenant_id)
    references public.eventos(id, tenant_id)
    on delete cascade,
  constraint evento_satisfaction_responses_question_tenant_fkey
    foreign key (question_id, tenant_id)
    references public.tenant_satisfaction_survey_questions(id, tenant_id)
    on delete cascade,
  constraint evento_satisfaction_responses_unique unique (evento_id, question_id)
);

create index tenant_satisfaction_survey_questions_tenant_idx
  on public.tenant_satisfaction_survey_questions (tenant_id, sort_order);

create index evento_satisfaction_responses_tenant_evento_idx
  on public.evento_satisfaction_responses (tenant_id, evento_id);

create trigger set_tenant_satisfaction_survey_questions_updated_at
before update on public.tenant_satisfaction_survey_questions
for each row execute function public.set_updated_at();

create trigger set_evento_satisfaction_responses_updated_at
before update on public.evento_satisfaction_responses
for each row execute function public.set_updated_at();

alter table public.tenant_satisfaction_survey_questions enable row level security;
alter table public.evento_satisfaction_responses enable row level security;

