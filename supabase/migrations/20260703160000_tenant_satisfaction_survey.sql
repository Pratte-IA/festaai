create or replace function public.seed_satisfaction_survey_on_tenant_create()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public.seed_tenant_satisfaction_survey_questions(new.id);
  return new;
end;
$$;

create trigger seed_satisfaction_survey_on_tenant_create
after insert on public.tenants
for each row
execute function public.seed_satisfaction_survey_on_tenant_create();

