-- ---------------------------------------------------------------------------
-- 8) RPC: opções de filtro + admins da plataforma
-- ---------------------------------------------------------------------------

create or replace function public.radar_crm_filter_options()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, radar
as $$
begin
  if not public.is_platform_admin() then
    raise exception 'Acesso negado: apenas administradores da plataforma.';
  end if;

  return jsonb_build_object(
    'cities', coalesce((
      select jsonb_agg(distinct city order by city)
      from radar.market_companies
      where city is not null and btrim(city) <> ''
    ), '[]'::jsonb),
    'states', coalesce((
      select jsonb_agg(distinct state order by state)
      from radar.market_companies
      where state is not null and btrim(state) <> ''
    ), '[]'::jsonb),
    'categories', coalesce((
      select jsonb_agg(distinct category order by category)
      from radar.market_companies
      where category is not null and btrim(category) <> ''
    ), '[]'::jsonb),
    'assignees', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', p.id,
          'full_name', p.full_name,
          'email', p.email
        )
        order by coalesce(p.full_name, p.email)
      )
      from public.profiles p
      where p.is_platform_admin = true
    ), '[]'::jsonb)
  );
end;
$$;

revoke all on function public.radar_crm_filter_options() from public, anon;
grant execute on function public.radar_crm_filter_options() to authenticated;
