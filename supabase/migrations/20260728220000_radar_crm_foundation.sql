create or replace function radar.crm_effective_status(p_status text, p_do_not_contact boolean)
returns text
language sql
immutable
as $$
  select case
    when coalesce(p_do_not_contact, false) then 'do_not_contact'
    when p_status is null or btrim(p_status) = '' then 'new'
    else p_status
  end;
$$;

create or replace function radar.crm_company_matches_search(p_company_id bigint, p_search text)
returns boolean
language sql
stable
as $$
  with term as (
    select nullif(lower(btrim(p_search)), '') as q
  )
  select
    case
      when (select q from term) is null then true
      else exists (
        select 1
        from radar.market_companies mc
        left join radar.company_cnpj_candidates cand
          on cand.company_id = mc.id
         and cand.is_selected = true
        where mc.id = p_company_id
          and (
            lower(coalesce(mc.name, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(mc.legal_name, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(mc.trade_name, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(cand.legal_name, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(cand.trade_name, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(cand.cnpj_data ->> 'legal_name', '')) like '%' || (select q from term) || '%'
            or lower(coalesce(cand.cnpj_data ->> 'trade_name', '')) like '%' || (select q from term) || '%'
            or (
              regexp_replace((select q from term), '[^0-9]', '', 'g') <> ''
              and regexp_replace(coalesce(mc.cnpj, ''), '[^0-9]', '', 'g')
                like '%' || regexp_replace((select q from term), '[^0-9]', '', 'g') || '%'
            )
            or (
              regexp_replace((select q from term), '[^0-9]', '', 'g') <> ''
              and regexp_replace(coalesce(mc.cnpj_formatted, ''), '[^0-9]', '', 'g')
                like '%' || regexp_replace((select q from term), '[^0-9]', '', 'g') || '%'
            )
            or lower(coalesce(mc.phone, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(mc.phone_unformatted, '')) like '%' || (select q from term) || '%'
            or lower(coalesce(mc.city, '')) like '%' || (select q from term) || '%'
            or exists (
              select 1
              from radar.company_partners cp
              where cp.company_id = mc.id
                and lower(coalesce(cp.partner_name, '')) like '%' || (select q from term) || '%'
            )
            or exists (
              select 1
              from radar.company_contacts cc
              where cc.company_id = mc.id
                and (
                  lower(coalesce(cc.display_value, '')) like '%' || (select q from term) || '%'
                  or lower(coalesce(cc.normalized_value, '')) like '%' || (select q from term) || '%'
                )
            )
          )
      )
    end;
$$;

