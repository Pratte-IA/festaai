-- Radar Comercial: tabelas de CRM, RLS no schema radar e RPCs para platform admin.
-- Não altera nem apaga dados das tabelas de coleta existentes.

-- ---------------------------------------------------------------------------
-- 1) Tabelas de acompanhamento comercial
-- ---------------------------------------------------------------------------

create table if not exists radar.company_crm (
  id bigint generated by default as identity primary key,
  company_id bigint not null references radar.market_companies (id) on delete cascade,
  status text not null default 'new'
    check (
      status = any (
        array[
          'new',
          'prospecting',
          'contacted',
          'responded',
          'meeting_scheduled',
          'proposal_sent',
          'won',
          'lost',
          'do_not_contact'
        ]
      )
    ),
  assigned_user_id uuid references public.profiles (id) on delete set null,
  priority text not null default 'medium'
    check (priority = any (array['high', 'medium', 'low'])),
  last_contact_at timestamptz,
  next_action_at timestamptz,
  next_action_description text,
  lost_reason text,
  do_not_contact boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint company_crm_company_id_key unique (company_id)
);

create table if not exists radar.company_crm_interactions (
  id bigint generated by default as identity primary key,
  company_id bigint not null references radar.market_companies (id) on delete cascade,
  interaction_type text not null
    check (
      interaction_type = any (
        array[
          'whatsapp',
          'phone',
          'instagram',
          'email',
          'meeting',
          'note',
          'other'
        ]
      )
    ),
  interaction_at timestamptz not null default now(),
  notes text,
  outcome text,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists company_crm_status_idx on radar.company_crm (status);
create index if not exists company_crm_priority_idx on radar.company_crm (priority);
create index if not exists company_crm_assigned_user_id_idx on radar.company_crm (assigned_user_id);
create index if not exists company_crm_next_action_at_idx on radar.company_crm (next_action_at);
create index if not exists company_crm_last_contact_at_idx on radar.company_crm (last_contact_at);
create index if not exists company_crm_do_not_contact_idx on radar.company_crm (do_not_contact);

create index if not exists company_crm_interactions_company_id_idx
  on radar.company_crm_interactions (company_id, interaction_at desc);
create index if not exists company_crm_interactions_created_by_idx
  on radar.company_crm_interactions (created_by);

create index if not exists market_companies_city_idx on radar.market_companies (city);
create index if not exists market_companies_state_idx on radar.market_companies (state);
create index if not exists market_companies_category_idx on radar.market_companies (category);
create index if not exists market_companies_cnpj_validation_status_idx
  on radar.market_companies (cnpj_validation_status);
create index if not exists market_companies_name_trgm_ready_idx
  on radar.market_companies (lower(name));

create index if not exists company_partners_company_decision_idx
  on radar.company_partners (company_id, decision_priority nulls last, is_administrator desc, partner_name);

create index if not exists company_contacts_company_whatsapp_idx
  on radar.company_contacts (company_id)
  where is_whatsapp = true or likely_whatsapp = true;

drop trigger if exists set_company_crm_updated_at on radar.company_crm;
create trigger set_company_crm_updated_at
before update on radar.company_crm
for each row
execute function public.set_updated_at();

