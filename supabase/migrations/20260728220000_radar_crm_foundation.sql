create or replace function public.radar_crm_get_company(p_company_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, radar
as $$
declare
  v_result jsonb;
begin
  if not public.is_platform_admin() then
    raise exception 'Acesso negado: apenas administradores da plataforma.';
  end if;

  select jsonb_build_object(
    'company', to_jsonb(mc) - 'cnpj_raw_data' - 'cnpj_candidate_data' - 'cnpj_validation_data' - 'cnpj_validation_reasons' - 'instagram_profiles',
    'crm', to_jsonb(crm),
    'assigned_user', case
      when assignee.id is null then null
      else jsonb_build_object(
        'id', assignee.id,
        'full_name', assignee.full_name,
        'email', assignee.email
      )
    end,
    'validated_cnpj', case
      when cand.id is null then null
      else jsonb_build_object(
        'id', cand.id,
        'cnpj', cand.cnpj,
        'cnpj_formatted', cand.cnpj_formatted,
        'legal_name', coalesce(cand.cnpj_data ->> 'legal_name', cand.legal_name),
        'trade_name', coalesce(cand.cnpj_data ->> 'trade_name', cand.trade_name),
        'registration_status', cand.cnpj_data ->> 'registration_status',
        'registration_status_normalized', cand.cnpj_data ->> 'registration_status_normalized',
        'is_active', (cand.cnpj_data ->> 'is_active')::boolean,
        'opening_date', cand.cnpj_data ->> 'opening_date',
        'legal_nature', cand.cnpj_data ->> 'legal_nature',
        'company_size', cand.cnpj_data ->> 'company_size',
        'mei_option', cand.cnpj_data ->> 'mei_option',
        'main_cnae_code', cand.cnpj_data ->> 'main_cnae_code',
        'main_cnae_description', cand.cnpj_data ->> 'main_cnae_description',
        'secondary_cnaes', coalesce(cand.cnpj_data -> 'secondary_cnaes', '[]'::jsonb),
        'city', cand.cnpj_data ->> 'city',
        'state', cand.cnpj_data ->> 'state',
        'full_address', cand.cnpj_data ->> 'full_address',
        'is_selected', cand.is_selected,
        'is_validated', cand.is_validated,
        'validation_status', cand.validation_status
      )
    end,
    'partners', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', cp.id,
          'partner_name', cp.partner_name,
          'qualification', cp.qualification,
          'is_administrator', cp.is_administrator,
          'is_probable_decision_maker', cp.is_probable_decision_maker,
          'decision_priority', cp.decision_priority,
          'age_range', cp.age_range,
          'joined_at', cp.joined_at,
          'partner_document_masked', cp.partner_document_masked,
          'source', cp.source
        )
        order by
          cp.decision_priority asc nulls last,
          cp.is_administrator desc,
          cp.is_probable_decision_maker desc,
          cp.partner_name asc
      )
      from radar.company_partners cp
      where cp.company_id = mc.id
    ), '[]'::jsonb),
    'contacts', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', cc.id,
          'contact_type', cc.contact_type,
          'display_value', cc.display_value,
          'normalized_value', cc.normalized_value,
          'is_whatsapp', cc.is_whatsapp,
          'likely_whatsapp', cc.likely_whatsapp,
          'is_primary', cc.is_primary
        )
        order by cc.is_primary desc, cc.is_whatsapp desc, cc.contact_order nulls last, cc.id
      )
      from radar.company_contacts cc
      where cc.company_id = mc.id
    ), '[]'::jsonb),
    'interactions', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', i.id,
          'interaction_type', i.interaction_type,
          'interaction_at', i.interaction_at,
          'notes', i.notes,
          'outcome', i.outcome,
          'created_by', i.created_by,
          'created_by_name', p.full_name,
          'created_by_email', p.email,
          'created_at', i.created_at
        )
        order by i.interaction_at desc, i.id desc
      )
      from radar.company_crm_interactions i
      left join public.profiles p on p.id = i.created_by
      where i.company_id = mc.id
    ), '[]'::jsonb)
  )
  into v_result
  from radar.market_companies mc
  left join radar.company_crm crm on crm.company_id = mc.id
  left join public.profiles assignee on assignee.id = crm.assigned_user_id
  left join lateral (
    select c.*
    from radar.company_cnpj_candidates c
    where c.company_id = mc.id
      and c.is_selected = true
    order by c.validated_at desc nulls last, c.id desc
    limit 1
  ) cand on true
  where mc.id = p_company_id;

  if v_result is null then
    raise exception 'Empresa não encontrada.';
  end if;

  return v_result;
end;
$$;

