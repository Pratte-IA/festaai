create or replace function public.radar_crm_add_interaction(
  p_company_id bigint,
  p_interaction_type text,
  p_notes text default null,
  p_outcome text default null,
  p_interaction_at timestamptz default null,
  p_status text default null,
  p_next_action_at timestamptz default null,
  p_next_action_description text default null,
  p_clear_next_action boolean default false,
  p_priority text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, radar
as $$
declare
  v_interaction radar.company_crm_interactions%rowtype;
  v_crm jsonb;
  v_at timestamptz := coalesce(p_interaction_at, now());
begin
  if not public.is_platform_admin() then
    raise exception 'Acesso negado: apenas administradores da plataforma.';
  end if;

  if not exists (select 1 from radar.market_companies where id = p_company_id) then
    raise exception 'Empresa não encontrada.';
  end if;

  insert into radar.company_crm_interactions (
    company_id,
    interaction_type,
    interaction_at,
    notes,
    outcome,
    created_by
  )
  values (
    p_company_id,
    p_interaction_type,
    v_at,
    p_notes,
    p_outcome,
    auth.uid()
  )
  returning * into v_interaction;

  v_crm := public.radar_crm_upsert_company(
    p_company_id := p_company_id,
    p_status := p_status,
    p_priority := p_priority,
    p_next_action_at := p_next_action_at,
    p_clear_next_action := p_clear_next_action,
    p_next_action_description := p_next_action_description,
    p_last_contact_at := v_at
  );

  return jsonb_build_object(
    'interaction', to_jsonb(v_interaction),
    'crm', v_crm
  );
end;
$$;

